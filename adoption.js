// A shuffled bag avoids repeats until every resident has appeared.
function adoptionBag(random=Math.random) {
  let bag=[],previous=null;
  return ()=>{
    if(!bag.length){
      bag=ADOPTION_CATALOG.map(p=>p.id);
      for(let i=bag.length-1;i>0;i--){const j=Math.floor(random()*(i+1));[bag[i],bag[j]]=[bag[j],bag[i]];}
      if(bag.at(-1)===previous)[bag[0],bag[bag.length-1]]=[bag[bag.length-1],bag[0]];
    }
    previous=bag.pop();return ADOPTION_CATALOG.find(p=>p.id===previous);
  };
}
